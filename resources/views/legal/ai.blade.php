<x-layouts.legal :title="__('About AI contacts')">
    <p><strong>Every contact in Call Joe is an AI companion, not a real person.</strong> Their names, faces, voices, families and life stories are made up. No human reads your texts or listens to your calls in real time.</p>

    <h2>What they are</h2>
    <ul>
        <li>Each contact's replies are written by a large language model, following a character written by our team and the relationship you choose (a sister, a best friend, a neighbor).</li>
        <li>Voices are synthetic. Faces and pictures are generated or licensed, never a real person's likeness without their consent.</li>
        <li>Contacts remember what you tell them in notes you can read and delete on each contact's "What they remember" page.</li>
        <li>If you sincerely ask a contact whether they're real, they'll tell you the truth: they're an AI.</li>
    </ul>

    <h2>What they can't do</h2>
    <ul>
        <li>They can make mistakes or make things up. Don't rely on them for medical, legal, financial or emergency advice.</li>
        <li>They can't call for help, and they aren't therapists.</li>
        <li>When they "text first" or "call" because they haven't heard from you, that's part of the character. You can turn it down or off for each contact, or use away mode.</li>
    </ul>

    <h2>If you're struggling</h2>
    <p>Please reach a real person. In the US, call or text <a href="tel:988">988</a> (the Suicide &amp; Crisis Lifeline) any time. If you or someone else is in danger right now, call 911. Outside the US, contact your local emergency number.</p>

    <h2>Adults only</h2>
    <p>Call Joe is for people 18 and over. Contacts never take part in anything sexual involving minors, never play younger, and never pretend to be a real person.</p>
</x-layouts.legal>
